export function getContentReadinessContent(language = "de") {
  return (
    contentReadinessContent[language] ??
    contentReadinessContent.de
  );
}

export function getContentReadinessOption(
  group,
  id,
  language = "de",
) {
  if (!id) return null;

  const content = getContentReadinessContent(language);

  return (
    content[group]?.find((option) => option.id === id) ??
    null
  );
}

export function normaliseReferenceUrl(value = "") {
  const trimmed = value.trim();

  if (!trimmed) return "";

  if (/^https?:\/\//i.test(trimmed)) {
    return trimmed;
  }

  return `https://${trimmed}`;
}

export function isValidReferenceUrl(value = "") {
  const trimmed = value.trim();

  /*
   * The reference fields are optional.
   */
  if (!trimmed) return true;

  try {
    const url = new URL(
      normaliseReferenceUrl(trimmed),
    );

    return Boolean(
      url.hostname &&
        url.hostname.includes("."),
    );
  } catch {
    return false;
  }
}