export function getTimelineSupportContent(
  language = "de",
) {
  return (
    timelineSupportContent[language] ??
    timelineSupportContent.de
  );
}

export function getTimelineOption(
  group,
  id,
  language = "de",
) {
  if (!id) return null;

  const content =
    getTimelineSupportContent(language);

  return (
    content[group]?.find(
      (option) => option.id === id,
    ) ?? null
  );
}